#!/usr/bin/env bun
// Post-build script: writes dist/_headers for Cloudflare Pages (origin A, PLAN §3.2).
//
// Why not Astro's `security.csp`: it emits a <meta> policy, which can't carry
// `frame-ancestors`, and it can't express `style-src-attr`, which the pages need
// for their `style="--x:…"` custom-property attributes (D-17). So the whole
// policy goes in one real header, with a sha256 for every inline <script> and
// <style> found in the built HTML.
//
// One `/*` rule, not one per page: Cloudflare joins headers from overlapping
// rules with a comma, which would turn two CSPs into two enforced policies.
// The hash set is the union over all pages, so it stays one line; the build
// fails if that line would pass Cloudflare's per-line limit.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const DIST = fileURLToPath(new URL("../dist/", import.meta.url));
// Legacy bundles from the old site. Nothing links to them since M1.2; they move to
// origin G or get deleted (owner call), so they are not covered by A's policy.
const SKIP_DIRS = new Set(["games"]);
const MAX_LINE = 2000;

// Script types the browser doesn't execute, so CSP doesn't apply to them.
const DATA_BLOCK_TYPES = new Set(["application/ld+json", "application/json", "importmap", "speculationrules"]);

const sha256 = (text) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

/** Returns the CSP hashes for every inline executable <script> and every <style> in `html`. */
export function inlineHashes(html) {
  const scripts = new Set();
  const styles = new Set();
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1];
    if (/\ssrc\s*=/i.test(attrs)) continue;
    const type = /\stype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && DATA_BLOCK_TYPES.has(type)) continue;
    scripts.add(sha256(m[2]));
  }
  for (const m of html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) styles.add(sha256(m[1]));
  return { scripts, styles };
}

/** Builds the policy string from hash sets. */
export function buildCsp({ scripts, styles }) {
  const list = (set) => [...set].sort().join(" ");
  return [
    "default-src 'self'",
    `script-src 'self' ${list(scripts)}`.trim(),
    `style-src 'self' ${list(styles)}`.trim(),
    // Inline custom-property attributes (`style="--x:3"`) on the boards, rings and grids.
    "style-src-attr 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

export function buildHeaders(csp) {
  return [
    "# Generated by scripts/build-headers.mjs. Don't edit dist/_headers by hand.",
    "/*",
    `  Content-Security-Policy: ${csp}`,
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=()",
    // HTML keeps Cloudflare Pages' default `public, max-age=0, must-revalidate`.
    "/_astro/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
  ].join("\n");
}

async function htmlFiles(dir, top = true) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (top && SKIP_DIRS.has(entry.name)) continue;
      out.push(...(await htmlFiles(path, false)));
    } else if (entry.name.endsWith(".html")) {
      out.push(path);
    }
  }
  return out;
}

async function main() {
  const files = await htmlFiles(DIST);
  if (files.length === 0) {
    console.error("[build-headers] no HTML in dist/ — run astro build first.");
    process.exit(1);
  }
  const all = { scripts: new Set(), styles: new Set() };
  for (const file of files) {
    const { scripts, styles } = inlineHashes(await readFile(file, "utf8"));
    for (const h of scripts) all.scripts.add(h);
    for (const h of styles) all.styles.add(h);
  }
  const csp = buildCsp(all);
  const headers = buildHeaders(csp);
  const longest = Math.max(...headers.split("\n").map((l) => l.length));
  if (longest > MAX_LINE) {
    console.error(
      `[build-headers] a _headers line is ${longest} chars (Cloudflare limit ${MAX_LINE}). ` +
        "Cut inline <style>/<script> blocks (e.g. build.inlineStylesheets: 'never').",
    );
    process.exit(1);
  }
  await writeFile(join(DIST, "_headers"), headers);
  console.log(
    `[build-headers] dist/_headers: ${files.length} pages, ${all.scripts.size} script + ${all.styles.size} style hashes, ` +
      `CSP ${csp.length} chars.`,
  );
}

if (import.meta.main) await main();
